// What is lastIndexOf()?
// The lastIndexOf() method searches for an element from the end of an array and returns the index of its last occurrence.
// Syntax
// array.lastIndexOf(searchElement, fromIndex);


// Parameters:
// Parameter	Meaning
// searchElement	Element to search for
// fromIndex	Optional. Index from which the backward search starts

// Return value:
// - Index of the last matching element.
// - -1 if the element is not found.
